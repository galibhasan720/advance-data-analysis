-- Find total customers by country
SELECT
	country,
	COUNT(DISTINCT customer_id) AS total_customers_by_coutry
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers_by_coutry DESC


-- Find total customers by gender
SELECT
	gender,
	COUNT(DISTINCT customer_id) AS total_customers_by_gender
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers_by_gender DESC


-- Find total products by category
SELECT
	ISNULL(category, 'n/a') AS category,
	COUNT(DISTINCT product_id) AS total_products_by_category
FROM gold.dim_products
GROUP BY category
ORDER BY total_products_by_category DESC


-- What is the average costs in each category?
SELECT
	ISNULL(category, 'n/a') AS category,
	AVG(cost) AS average_cost_by_category
FROM gold.dim_products
GROUP BY category
ORDER BY average_cost_by_category DESC

-- What is the total revenue generated for each category?
SELECT
	ISNULL(pr.category,'n/a') AS category,
	COALESCE(SUM(fc.sales_amount),0) AS total_revenue
FROM gold.fact_sales fc 
LEFT JOIN gold.dim_products pr 
ON pr.product_key = fc.product_key
GROUP BY category
ORDER BY total_revenue DESC

-- Find total revenue is generated by each customer
SELECT
	c.customer_key,
	c.first_name,
	c.last_name,
	COALESCE(SUM(f.sales_amount),0) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY 
	c.customer_key,
	c.first_name,
	c.last_name
ORDER BY total_revenue DESC

-- What is the distribution of sold items across countries?
SELECT
ISNULL(cs.country,'n/a') AS countries,
COALESCE(SUM(fs.quantity), 0) AS sold_item
FROM gold.fact_sales fs
FULL JOIN gold.dim_customers cs
ON cs.customer_key = fs.customer_key
GROUP BY cs.country 
ORDER BY sold_item DESC

